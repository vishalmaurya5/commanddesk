export function permissionsForRole(role: string, customPermissions: string[] = []) {
  return Array.from(new Set([...(ROLE_PERMISSIONS[role] ?? []), ...customPermissions]));
}

export function roleHasPermission(
  role: string,
  permission: Permission,
  customPermissions: string[] = [],
) {
  return permissionsForRole(role, customPermissions).includes(permission);
}
